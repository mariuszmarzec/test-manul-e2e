def add(a: float, b: float) -> float:
    """
    Add two numbers and return the result.
    
    Args:
        a (float): The first number to add
        b (float): The second number to add
    
    Returns:
        float: The sum of a and b
        
    Example:
        >>> add(2, 3)
        5.0
        >>> add(1.5, 2.5)
        4.0
    """
    return a + b